//! Node project builds for TypeScript packages (`faber build --target ts`).
//!
//! The build writes one self-contained project under `target/faber/ts`:
//!
//! ```text
//! package.json   tsconfig.json   src/**/*.ts   dist/**/*.js
//! node_modules/@faber/runtime/   bin/<name>.js
//! ```
//!
//! The command lines come from the merged backend recipe
//! ([`super::ts_recipe`]), the runtime is the compiled copy of the one embedded
//! in `faber` ([`super::ts_runtime`]), and `tsc` / `node` come from `PATH`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitStatus};

use radix::module::diagnostics::Diagnostic;
use radix::module::driver::Config;
use radix::program::discovery::BuildLayout;

use super::build_recipe::{exit_code_of, sanitize_file_stem};
use super::ts_project::{
    TS_TARGET, TsProjectFiles, generate_ts_library_files, generate_ts_project_files,
};
use super::ts_recipe::{TsRecipe, require_tool};
use super::ts_runtime::{compiled_runtime, install_runtime};

/// Declares the Node globals generated code may use, so a build needs no
/// `@types/node` on the machine (the recipe sets `types = []`).
const NODE_ENV_DECLARATIONS: &str =
    "// Generated by faber: Node globals used by built programs.\ndeclare const process: any;\n";

/// A built Node project.
pub(crate) struct TsProgram {
    pub root: PathBuf,
    pub launcher: PathBuf,
    pub recipe: TsRecipe,
}

fn build_error(message: impl Into<String>) -> Diagnostic {
    crate::package_diagnostic_error(message).with_arg("issue", "package_ts_build_failed")
}

fn io_error(action: &str, path: &Path, err: &std::io::Error) -> Diagnostic {
    build_error(format!("failed to {action} '{}': {err}", path.display()))
}

/// `<package>/target/faber/ts`.
fn project_root(layout: &BuildLayout) -> PathBuf {
    layout.cargo_target_dir.join("faber").join("ts")
}

/// Build the package at `input` into a Node project and return it.
///
/// # Errors
/// Returns the diagnostics of analysis, codegen, a missing tool, or a failed
/// `tsc` run.
pub(crate) fn build_ts_program(
    config: &Config,
    input: &Path,
    layout: &BuildLayout,
) -> Result<TsProgram, Vec<Diagnostic>> {
    let files = radix::program::emit::package_rust_runtime_plan(
        config,
        input,
        &super::faber_analysis_seams(),
        |package, _| {
            Ok(generate_ts_project_files(package).and_then(|mut files| {
                files
                    .files
                    .extend(generate_ts_library_files(package, config)?);
                Ok(files)
            }))
        },
    )??;

    let runtime_root = super::embedded_runtime::embedded_runtime_root().ok_or_else(|| {
        vec![build_error(
            "the embedded TypeScript runtime could not be materialized",
        )]
    })?;
    let manifest = if layout.manifest_path.exists() {
        Some(super::read_manifest(&layout.manifest_path).map_err(|diag| vec![*diag])?)
    } else {
        None
    };
    let recipe = TsRecipe::backend_default(&runtime_root)
        .map_err(|diag| vec![diag])?
        .with_project(
            manifest
                .as_ref()
                .and_then(|manifest| manifest.target.get("ts")),
        );

    // Name a missing build tool before any file is written.
    require_tool(&recipe.build).map_err(|diag| vec![diag])?;

    let name = sanitize_file_stem(layout.binary_name());
    let root = project_root(layout);
    let compiled = compiled_runtime(&runtime_root).map_err(|diag| vec![diag])?;
    write_project(&root, &name, &files, &recipe, &compiled).map_err(|diag| vec![diag])?;

    run_build(&recipe, &root).map_err(|diag| vec![diag])?;

    let launcher = root.join("bin").join(format!("{name}.js"));
    if !launcher.is_file() {
        return Err(vec![build_error(format!(
            "the build left no launcher at '{}'",
            launcher.display()
        ))]);
    }
    Ok(TsProgram {
        root,
        launcher,
        recipe,
    })
}

fn write_project(
    root: &Path,
    name: &str,
    files: &TsProjectFiles,
    recipe: &TsRecipe,
    compiled_runtime_dir: &Path,
) -> Result<(), Diagnostic> {
    // The generated source and output trees are owned by the build: stale
    // files from an earlier layout must not survive into this one.
    for owned in ["src", "dist", "bin"] {
        let dir = root.join(owned);
        if dir.exists() {
            fs::remove_dir_all(&dir).map_err(|err| io_error("clear", &dir, &err))?;
        }
    }
    let write = |relative: &Path, text: &str| -> Result<(), Diagnostic> {
        let path = root.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|err| io_error("create", parent, &err))?;
        }
        fs::write(&path, text).map_err(|err| io_error("write", &path, &err))
    };

    let package_json = serde_json::json!({
        "name": name,
        "version": "0.0.0",
        "private": true,
        "type": "module",
        "bin": { name: format!("bin/{name}.js") },
    });
    let package_json = serde_json::to_string_pretty(&package_json)
        .map_err(|err| build_error(format!("cannot render package.json: {err}")))?;
    write(Path::new("package.json"), &format!("{package_json}\n"))?;
    write(Path::new("tsconfig.json"), &recipe.tsconfig())?;
    write(Path::new("src/faber-env.d.ts"), NODE_ENV_DECLARATIONS)?;
    for file in &files.files {
        write(&Path::new("src").join(&file.path), &file.code)?;
    }
    install_runtime(compiled_runtime_dir, root)?;

    let entry_js = files.entry.with_extension("js");
    let launcher = format!(
        "#!/usr/bin/env node\nimport \"../dist/{}\";\n",
        entry_js.to_string_lossy().replace('\\', "/")
    );
    write(&Path::new("bin").join(format!("{name}.js")), &launcher)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let path = root.join("bin").join(format!("{name}.js"));
        fs::set_permissions(&path, fs::Permissions::from_mode(0o755))
            .map_err(|err| io_error("mark executable", &path, &err))?;
    }
    Ok(())
}

fn run_build(recipe: &TsRecipe, root: &Path) -> Result<(), Diagnostic> {
    let tool = require_tool(&recipe.build)?;
    let output = Command::new(&tool)
        .args(&recipe.build[1..])
        .current_dir(root)
        .output()
        .map_err(|err| build_error(format!("failed to execute `{}`: {err}", recipe.build[0])))?;
    if output.status.success() {
        return Ok(());
    }
    Err(build_error(format!(
        "`{}` failed for '{}':\n{}{}",
        recipe.build.join(" "),
        root.display(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )))
}

/// Run a built program with `args`, streams inherited. Fails by name when
/// the run tool (`node`) is not on `PATH`.
///
/// # Errors
/// Returns a diagnostic when the run tool is missing or cannot start.
pub(crate) fn run_ts_program(
    program: &TsProgram,
    args: &[String],
) -> Result<ExitStatus, Diagnostic> {
    let argv = program.recipe.run_argv(&program.launcher);
    let tool = require_tool(&argv)?;
    Command::new(&tool)
        .args(&argv[1..])
        .args(args)
        .current_dir(std::env::current_dir().unwrap_or_else(|_| program.root.clone()))
        .status()
        .map_err(|err| build_error(format!("failed to execute `{}`: {err}", argv[0])))
}

/// `faber run --target ts`: build the package, run it with `program_args`,
/// and exit with the program's own status. Standard streams pass straight
/// through; the build prints nothing on stdout.
pub fn cmd_run_ts(
    input: &Path,
    locale: Option<&str>,
    diagnostics_locale: Option<&str>,
    program_args: &[String],
    diagnostic_mode: radix::services::DiagnosticMode,
) -> ! {
    let input = super::absolutize_path(input);
    let (config, locale_pack) =
        match super::config_with_locale(TS_TARGET, &input, locale, diagnostics_locale) {
            Ok(pair) => pair,
            Err(diag) => crate::package::build_recipe::report_run_and_exit_mode(
                std::slice::from_ref(&*diag),
                None,
                diagnostic_mode,
            ),
        };
    // A single `.fab` file has no package of its own: its project goes to a
    // scratch directory instead of beside the source.
    let scratch = std::env::temp_dir().join("faber-run-ts");
    let layout = match super::cmd::discover_build_layout(&input, &scratch) {
        Ok(layout) => layout,
        Err(diag) => crate::package::build_recipe::report_run_and_exit_mode(
            std::slice::from_ref(&*diag),
            locale_pack.as_ref(),
            diagnostic_mode,
        ),
    };
    let program = match build_ts_program(&config, &input, &layout) {
        Ok(program) => program,
        Err(diagnostics) => crate::package::build_recipe::report_run_and_exit_mode(
            &diagnostics,
            locale_pack.as_ref(),
            diagnostic_mode,
        ),
    };
    match run_ts_program(&program, program_args) {
        Ok(status) => std::process::exit(exit_code_of(status)),
        Err(diag) => crate::package::build_recipe::report_run_and_exit_mode(
            std::slice::from_ref(&diag),
            locale_pack.as_ref(),
            diagnostic_mode,
        ),
    }
}

