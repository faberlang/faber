//! The runtime's `extern "C"` entry points as an explicit symbol table.
//!
//! A JIT-compiled image resolves every runtime import from this table rather
//! than looking symbols up in the process, so what a program can call is
//! exactly what is listed here. `tests/symbol_table.rs` keeps the table equal to
//! the exports in the sources, and the generator's `abi::RUNTIME_SYMBOLS` agrees
//! with both (`radix-mir-clif/tests/abi_symbols.rs`).

use crate as root;
use crate::{dec, format_rt, inf, ins, regex_rt, sermo};

macro_rules! sym {
    ($module:ident, $name:ident) => {
        (stringify!($name), $module::$name as *const u8)
    };
}

